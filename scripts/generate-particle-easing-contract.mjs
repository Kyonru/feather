/**
 * Freeze the particle easing curves as a cross-language contract.
 *
 * The easing maths exists in two languages: `core.lua` drives what plays, and
 * `easing.ts` draws the curve you see in the editor. Nothing connected them, so
 * a change to one would silently make the curve you author differ from the
 * curve that runs. They agree today — this pins that.
 *
 * `core.lua` is the authority: it is what ships inside the game. Regenerate
 * only when the curves are meant to change, and expect both suites to fail
 * until each side is updated.
 *
 *   node scripts/generate-particle-easing-contract.mjs
 *
 * Requires a Lua interpreter (`lua`, `lua5.4` or `luajit`) — generation only,
 * never at test time.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const corePath = path.join(root, 'packages/runtime-lua/plugins/particle-system-playground/core.lua');
const outPath = path.join(root, 'scripts/tests/fixtures/particle-easing-contract.json');
const SAMPLES = 21;

const program = `
local core = dofile(${JSON.stringify(corePath)})
local names = {}
for name in pairs(core.EASINGS) do names[#names + 1] = name end
table.sort(names)
local parts = {}
for _, name in ipairs(names) do
  local values = {}
  for i = 0, ${SAMPLES - 1} do
    values[#values + 1] = string.format("%.6f", core.ease(name, i / ${SAMPLES - 1}))
  end
  parts[#parts + 1] = string.format("%q: [%s]", name, table.concat(values, ", "))
end
io.write("{\\n  " .. table.concat(parts, ",\\n  ") .. "\\n}")
`;

let lua = null;
for (const candidate of ['lua', 'lua5.4', 'luajit']) {
  try {
    execFileSync(candidate, ['-v'], { stdio: 'ignore' });
    lua = candidate;
    break;
  } catch {
    // try the next one
  }
}
if (!lua) {
  console.error('No Lua interpreter found (tried lua, lua5.4, luajit).');
  process.exit(1);
}

const curves = JSON.parse(execFileSync(lua, ['-e', program], { encoding: 'utf8' }));
writeFileSync(
  outPath,
  `${JSON.stringify(
    {
      _comment:
        'Generated by scripts/generate-particle-easing-contract.mjs from core.lua. ' +
        'Asserted by scripts/tests/particleEasingContract.test.ts (easing.ts) and by the Lua e2e suite (core.lua). ' +
        'Do not hand-edit.',
      samples: SAMPLES,
      curves,
    },
    null,
    2,
  )}\n`,
);
console.log(`Written ${path.relative(root, outPath)} (${Object.keys(curves).length} easings x ${SAMPLES} samples)`);
