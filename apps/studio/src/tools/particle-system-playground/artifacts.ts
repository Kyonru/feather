import type {
  ParticleSystemPlaygroundData,
  ParticleSystemPlaygroundProjectFile,
} from '@studio/types/particle-system-playground';
import {
  PARTICLE_PROJECT_TYPE,
  PARTICLE_PROJECT_VERSION,
  withNormalizedTimeline,
} from './timeline';

type JsonRecord = Record<string, unknown>;

export function safeParticleFilename(name: string): string {
  return name.replace(/[^a-zA-Z0-9._-]+/g, '-').replace(/^-+|-+$/g, '') || 'particle-effect';
}

export function projectForLocalParticleData(data: ParticleSystemPlaygroundData): ParticleSystemPlaygroundProjectFile {
  if (!data.data || !data.activeComposite) throw new Error('Create or import a particle composite first.');
  const { compositeType: _compositeType, timelineState: _timelineState, ...composite } = withNormalizedTimeline(data.data);
  return {
    type: PARTICLE_PROJECT_TYPE,
    version: PARTICLE_PROJECT_VERSION,
    exportedAt: new Date().toISOString(),
    name: data.activeComposite,
    composite,
  };
}

function luaString(value: string): string {
  return JSON.stringify(value).replace(/\u2028|\u2029/g, ' ');
}

function luaLiteral(value: unknown, depth = 0): string {
  if (depth > 24) throw new Error('Particle project is too deeply nested to export.');
  if (value === null || value === undefined) return 'nil';
  if (typeof value === 'boolean' || typeof value === 'number') return String(value);
  if (typeof value === 'string') return luaString(value);
  if (Array.isArray(value)) return `{ ${value.map((item) => luaLiteral(item, depth + 1)).join(', ')} }`;
  if (typeof value === 'object') {
    return `{ ${Object.entries(value as JsonRecord)
      .filter(([, item]) => item !== undefined)
      .map(([key, item]) => `[${luaString(key)}] = ${luaLiteral(item, depth + 1)}`)
      .join(', ')} }`;
  }
  throw new Error(`Cannot export particle value of type ${typeof value}.`);
}

export function exportParticleProject(data: ParticleSystemPlaygroundData) {
  const project = projectForLocalParticleData(data);
  const filename = `${safeParticleFilename(project.name)}.featherparticles`;
  return { filename, project, content: JSON.stringify(project, null, 2) };
}

export function exportParticleLua(data: ParticleSystemPlaygroundData, texturePathsBySystem: Record<number, string> = {}) {
  const project = projectForLocalParticleData(data);
  const composite = {
    ...project.composite,
    systems: project.composite.systems.map(({ textureAssetBase64: _asset, ...system }) => ({
      ...system,
      texturePath: texturePathsBySystem[system.index] ?? system.texturePath,
    })),
  };
  const source = [
    '-- Generated by Feather Studio. This is the authored particle definition.',
    '-- Feed the returned table into your project particle factory/runtime.',
    `local effect = ${luaLiteral(composite)}`,
    '',
    'return effect',
    '',
  ].join('\n');
  return { filename: `${safeParticleFilename(project.name)}.lua`, source };
}

function bytesFromBase64(value: string): Uint8Array {
  const binary = atob(value);
  return Uint8Array.from(binary, (character) => character.charCodeAt(0));
}

function uniqueArchivePath(path: string, seen: Set<string>): string {
  if (!seen.has(path)) {
    seen.add(path);
    return path;
  }
  const dot = path.lastIndexOf('.');
  const base = dot > path.lastIndexOf('/') ? path.slice(0, dot) : path;
  const extension = dot > path.lastIndexOf('/') ? path.slice(dot) : '';
  let suffix = 2;
  while (seen.has(`${base}-${suffix}${extension}`)) suffix += 1;
  const next = `${base}-${suffix}${extension}`;
  seen.add(next);
  return next;
}

export function particleProjectZipEntries(data: ParticleSystemPlaygroundData): Record<string, Uint8Array> {
  const project = exportParticleProject(data);
  const archive: Record<string, Uint8Array> = {
    [`${safeParticleFilename(project.project.name)}.featherparticles`]: new TextEncoder().encode(project.content),
  };
  const seen = new Set(Object.keys(archive));
  const texturePathsBySystem: Record<number, string> = {};

  for (const system of project.project.composite.systems) {
    if (system.shaderSource) {
      const filename = safeParticleFilename(system.shaderFilename || `emitter-${system.index}.glsl`);
      const path = uniqueArchivePath(`shaders/${filename}`, seen);
      archive[path] = new TextEncoder().encode(system.shaderSource);
    }
    if (system.textureAssetBase64) {
      const filename = safeParticleFilename(system.textureFilename || `emitter-${system.index}.png`);
      const path = uniqueArchivePath(`textures/${filename}`, seen);
      archive[path] = bytesFromBase64(system.textureAssetBase64);
      texturePathsBySystem[system.index] = path;
      if (system.textureAtlas) {
        const atlasPath = path.replace(/\.[^/.]+$/, '') + '.atlas.json';
        archive[uniqueArchivePath(atlasPath, seen)] = new TextEncoder().encode(JSON.stringify(system.textureAtlas, null, 2));
      }
    }
  }
  const code = exportParticleLua(data, texturePathsBySystem);
  archive[code.filename] = new TextEncoder().encode(code.source);
  return archive;
}
